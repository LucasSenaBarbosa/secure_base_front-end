const DEGREE = [0x00, 0x06, 0x09, 0x09, 0x06];

function columns(ch: string) {
  if (ch === '°') return DEGREE;
  const plain = ch.normalize('NFD').replace(/[\u0300-\u036f]/g, '');
  const code = plain.charCodeAt(0);
  if (code < 0x20 || code > 0x7e) return FONT.slice(0, 5);
  const i = (code - 0x20) * 5;
  return FONT.slice(i, i + 5);
}

export const LCD_W = 768;
export const LCD_H = 228;

const PALETTE = {
  on: { bg: '#1f3fd6', off: 'rgba(120,150,255,0.16)', dot: '#eaf1ff', glow: 'rgba(200,220,255,0.55)' },
  off: { bg: '#0a1236', off: 'rgba(120,150,255,0.05)', dot: '#5262a0', glow: 'transparent' },
};

export function drawLcd(ctx: CanvasRenderingContext2D, lines: [string, string], backlight: boolean, w = LCD_W, h = LCD_H) {
  const pal = backlight ? PALETTE.on : PALETTE.off;
  const pitch = Math.min(w / 101, h / 24);
  const dot = pitch * 0.86;
  const ox = (w - pitch * 95) / 2;
  const oy = (h - pitch * 17) / 2;

  const grad = ctx.createLinearGradient(0, 0, 0, h);
  grad.addColorStop(0, pal.bg);
  grad.addColorStop(1, backlight ? '#1733b8' : '#070d28');
  ctx.fillStyle = grad;
  ctx.fillRect(0, 0, w, h);

  for (let row = 0; row < 2; row++) {
    const text = lines[row] ?? '';
    for (let col = 0; col < 16; col++) {
      const cols = columns(text[col] ?? ' ');
      for (let cx = 0; cx < 5; cx++) {
        for (let cy = 0; cy < 8; cy++) {
          const lit = cy < 7 && (cols[cx] >> cy) & 1;
          const x = ox + (col * 6 + cx) * pitch;
          const y = oy + (row * 9 + cy) * pitch;
          if (lit) {
            ctx.shadowColor = pal.glow;
            ctx.shadowBlur = pitch * 0.9;
            ctx.fillStyle = pal.dot;
          } else {
            ctx.shadowBlur = 0;
            ctx.fillStyle = pal.off;
          }
          ctx.fillRect(x, y, dot, dot);
        }
      }
    }
  }
  ctx.shadowBlur = 0;
}
